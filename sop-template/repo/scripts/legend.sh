#!/bin/sh
# legend.sh — read-only: one markdown table per owner, one row per repository, showing how each repository is guarded.
#   sh scripts/legend.sh <owner> [<owner>...]                 # every repository the signed-in gh account can see
#   sh scripts/legend.sh --public-only <owner> [<owner>...]   # public repositories only (safe to paste into a public page)
# "not on this plan": GitHub Free offers no rulesets or branch protection on private repositories (organisation or personal).
# Rulesets show name:enforcement[rule types]; a twin should show [deletion] only, a strict one also non_fast_forward.
# Columns: visibility · default branch · has a preview branch · rulesets (name:enforcement) · merge methods allowed · Pages · public twin.
# "Public twin" is read from the name (ends -public, -public-preview or -publish-preview): those receive a sync or a site build and
# carry only a deletion-only ruleset, because the sync force-pushes. Merge methods need admin on the repository; "?" means not visible.
# Needs: gh (signed in), python3. Changes nothing: every call is a GET. Each call is time-limited (the resolver stalls; SOP-IT-001).
set -eu
PUBLIC_ONLY=0
if [ "${1:-}" = "--public-only" ]; then PUBLIC_ONLY=1; shift; fi
[ $# -ge 1 ] || { echo "usage: sh scripts/legend.sh [--public-only] <owner> [<owner>...]" >&2; exit 2; }
api () { perl -e 'alarm 40; exec @ARGV' gh api "$@" 2>/dev/null; }
echo "<!-- generated by scripts/legend.sh on $(date -u +%Y-%m-%dT%H:%MZ); regenerate, do not hand-edit -->"
for owner in "$@"; do
  # an organisation or a user: try the organisation route first
  if api "orgs/$owner" >/dev/null; then route="orgs/$owner/repos?type=all&per_page=100"
  elif [ "$owner" = "$(api user --jq .login)" ]; then route="user/repos?affiliation=owner&per_page=100"
  else route="users/$owner/repos?per_page=100"; fi
  echo ""
  echo "### $owner"
  echo ""
  echo "| Repository | Visibility | Default | preview branch | Rulesets | Merge methods | Pages | Public twin |"
  echo "|---|---|---|---|---|---|---|---|"
  api --paginate "$route" --jq '.[] | select(.archived|not) | select(.owner.login=="'"$owner"'") | [.name, .visibility, .default_branch, (.has_pages|tostring)] | @tsv' | sort |
  while IFS="$(printf '\t')" read -r name vis def pages; do
    [ "$PUBLIC_ONLY" = 1 ] && [ "$vis" != "public" ] && continue
    full="$owner/$name"
    if api "repos/$full/branches/preview" >/dev/null; then prev="yes"; else prev="—"; fi
    if raw="$(perl -e 'alarm 40; exec @ARGV' gh api "repos/$full/rulesets" 2>/dev/null)"; then
      rules=""
      for id in $(printf '%s' "$raw" | python3 -I -c 'import sys,json; print(" ".join(str(r["id"]) for r in json.load(sys.stdin)))'); do
        one="$(api "repos/$full/rulesets/$id" --jq '"\(.name):\(.enforcement)[\([.rules[].type] | join("+"))]"' || echo "?")"
        rules="${rules:+$rules, }$one"
      done
      [ -n "$rules" ] || rules="—"
    else
      case "$raw" in *Upgrade*) rules="not on this plan";; *) rules="?";; esac
    fi
    merge="$(api "repos/$full" --jq '[ (if .allow_merge_commit == true then "merge" else empty end), (if .allow_squash_merge == true then "squash" else empty end), (if .allow_rebase_merge == true then "rebase" else empty end) ] | if length == 0 then "?" else join(", ") end' || echo "?")"
    case "$pages" in true) pg="yes";; *) pg="—";; esac
    case "$name" in *-public|*-public-preview|*-publish-preview) twin="yes";; *) twin="—";; esac
    echo "| \`$name\` | $vis | \`$def\` | $prev | $rules | $merge | $pg | $twin |"
  done
done
